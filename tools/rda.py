"""The agent's loop tool (not part of the ruler): score a solution, record it, refresh PROGRESS.md and status.json.

    python3 tools/rda.py evaluate <solution> [--directory live|main] [--inputs saved.json]
    python3 tools/rda.py progress            # regenerate PROGRESS.md + status.json from ledger.jsonl

`evaluate` collects the inputs with the frozen scorer (or re-scores a saved inputs file), saves them beside the
solution (solutions/<id>/runs/<t>.inputs.json, so any score can be re-derived offline), writes its scorecard.json,
and appends one row to ledger.jsonl.
"""

from __future__ import annotations

import json
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from scorer import RULER  # noqa: E402
from scorer.collect import collect  # noqa: E402
from scorer.score import GATES, score  # noqa: E402

LEDGER = REPO / "ledger.jsonl"
LIST_METRICS = ("unlisted_repos", "undeclared_packages", "dead_links", "ci_not_green", "pypi_mismatch")


def commit() -> str | None:
    done = subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True, text=True)
    return done.stdout.strip() or None


def evaluate(solution: str, directory: str, saved: str | None) -> dict:
    folder = REPO / "solutions" / solution
    meta = json.loads((folder / "meta.json").read_text(encoding="utf-8"))
    inputs = json.loads(Path(saved).read_text(encoding="utf-8")) if saved else collect(directory)
    card = score(inputs)
    stamp = inputs["collected"].replace(":", "").replace("+0000", "Z")
    runs = folder / "runs"
    runs.mkdir(exist_ok=True)
    inputs_path = runs / f"{stamp}.inputs.json"
    inputs_path.write_text(json.dumps(inputs, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    (folder / "scorecard.json").write_text(json.dumps(card, indent=1) + "\n", encoding="utf-8")
    m = card["metrics"]
    row = {
        "t": inputs["collected"],
        "solution": solution,
        "parent": meta.get("parent"),
        "ruler": RULER,
        "directory": inputs.get("directory"),
        "objective": card["objective"]["value"],
        "admissible": card["admissible"],
        "gate_pass_rate": card["gate_pass_rate"],
        "gates": card["gates"],
        "failed_gates": card["failed_gates"],
        "metrics": {
            "max_stale_hours": m["max_stale_hours"],
            "stale_packages": m["stale_packages"],
            "listed": m["listed"],
            "lint_failures": m["lint_failures"],
            "lint_pass_rate": m["lint_pass_rate"],
            "graph_matches_rebuild": m["graph_matches_rebuild"],
            "site_serves_graph": m["site_serves_graph"],
            "site_page_matches_main": m["site_page_matches_main"],
            "links_checked": m["links_checked"],
            **{k: (len(m[k]) if isinstance(m[k], list) else None) for k in LIST_METRICS},
        },
        "inputs": inputs_path.relative_to(REPO).as_posix(),
        "evidence": meta.get("evidence"),
        "repo_commit": commit(),
        "proposed_by": meta.get("proposed_by"),
        "change": meta.get("change"),
    }
    with LEDGER.open("a", encoding="utf-8") as ledger:
        ledger.write(json.dumps(row) + "\n")
    progress()
    return card


def rows() -> list[dict]:
    if not LEDGER.exists():
        return []
    return [json.loads(line) for line in LEDGER.read_text(encoding="utf-8").splitlines() if line.strip()]


def fmt(value: object) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def rank_key(row: dict) -> tuple:
    objective = row["objective"] if row["objective"] is not None else float("inf")
    return (not row["admissible"], -row["gate_pass_rate"], objective)


def progress() -> None:
    ledger = rows()
    newest: dict[str, dict] = {}
    for row in ledger:
        if row.get("ruler") == RULER:  # rows scored on an older ruler stay in the ledger, never in the ranking
            newest[row["solution"]] = row
    ranked = sorted(newest.values(), key=rank_key)
    best = ranked[0] if ranked else None
    lines = [
        "# Progress",
        "",
        f"Generated by `python3 tools/rda.py progress` from `ledger.jsonl` (ruler {RULER}); never edit by hand.",
        "",
    ]
    if best:
        passed = sum(best["gates"].values())
        lines += [
            f"**Best: `{best['solution']}`**, {passed} of {len(GATES)} gates, worst staleness "
            f"**{fmt(best['objective'])} h** ({'admissible' if best['admissible'] else 'not admissible: ' + ', '.join(best['failed_gates'])}), "
            f"scored {best['t']}.",
            "",
            "## Solutions (newest score of each, best first)",
            "",
            "| solution | scored | max stale (h) | gates passed | failed gates |",
            "|---|---|---|---|---|",
        ]  # fmt: skip
        for row in ranked:
            lines.append(f"| `{row['solution']}` | {row['t']} | {fmt(row['objective'])} | "
                         f"{sum(row['gates'].values())}/{len(GATES)} | {', '.join(row['failed_gates']) or '—'} |")  # fmt: skip
        lines += ["", "## Gate matrix (newest score of each)", "",
                  "| solution | " + " | ".join(f"`{g}`" for g in GATES) + " |",
                  "|---|" + "---|" * len(GATES)]  # fmt: skip
        for row in ranked:
            lines.append(f"| `{row['solution']}` | " + " | ".join("pass" if row["gates"][g] else "**fail**" for g in GATES) + " |")
        lines += ["", "## Last 10 ledger rows", "",
                  "| t | solution | directory | max stale (h) | lint fails | unlisted | undeclared | dead links | CI not green | PyPI behind |",
                  "|---|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
        for row in ledger[-10:]:
            m = row["metrics"]
            lines.append(f"| {row['t']} | `{row['solution']}` | {row['directory']} | {fmt(row['objective'])} | "
                         f"{fmt(m['lint_failures'])} | {fmt(m['unlisted_repos'])} | {fmt(m['undeclared_packages'])} | "
                         f"{fmt(m['dead_links'])} | {fmt(m['ci_not_green'])} | {fmt(m['pypi_mismatch'])} |")  # fmt: skip
    (REPO / "PROGRESS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    status(best, ledger)


def status(best: dict | None, ledger: list[dict]) -> None:
    ideas = (REPO / "ideas.md").read_text(encoding="utf-8") if (REPO / "ideas.md").exists() else ""
    open_ideas = [line[6:].strip() for line in ideas.splitlines() if line.startswith("- [ ] ")]
    failed = best["failed_gates"] if best else list(GATES)
    data = {
        "schema": "ai-team-status/1",
        "member": "Robot SDK Agent",
        "team": "Robot Team",
        "remit": f"keep robot-sdk a true, current directory of the robot-* packages, inside the gates (ruler {RULER}, OBJECTIVES.md)",
        "kpi": {
            "name": "max_stale_hours (worst listed repo: hours since the first push the live graph missed)",
            "value": best["objective"] if best else None,
            "unit": "h",
            "direction": "down",
            "target": 24,
            "level": f"{sum(best['gates'].values())} of {len(GATES)} gates" if best else f"0 of {len(GATES)} gates",
            "level_name": f"ruler {RULER} · live directory",
            "next_gate": failed[0] if failed else None,
            "on_track": bool(best and best["gates"]["fresh_24h"]),
        },
        "counter_kpi": {
            "name": "gates failed by the best solution",
            "value": len(failed),
            "unit": "gates",
            "owner": "Robot SDK Agent",
        },
        "status": "idle",
        "blocked_on": None,
        "todo": {"open": len(open_ideas), "done_7d": sum(1 for line in ideas.splitlines() if line.startswith("- [x]")),
                 "top": open_ideas[:3]},  # fmt: skip
        "links": {
            "repo": "https://github.com/zacharyyamaoka/robot_sdk_agent",
            "report": "PROGRESS.md",
            "wandb": None,
            "vault": None,
        },
        "updated_t": time.time(),
    }
    (REPO / "status.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    if argv[:1] == ["evaluate"] and len(argv) >= 2:
        directory = argv[argv.index("--directory") + 1] if "--directory" in argv else "live"
        saved = argv[argv.index("--inputs") + 1] if "--inputs" in argv else None
        card = evaluate(argv[1], directory, saved)
        print(json.dumps({k: card[k] for k in ("objective", "admissible", "gate_pass_rate", "failed_gates")}, indent=1))
        return 0
    if argv[:1] == ["progress"]:
        progress()
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
